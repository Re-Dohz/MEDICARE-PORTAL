/* Team Check: notes every red error a portal file throws while it loads.
   You do not edit this file. It uses things after Day 13; you do not need to read it. */
var CHECK_ERRORS = [];
window.onerror = function (message, source, line) {
  var file = String(source || "").split("/").pop() || "a file";
  CHECK_ERRORS.push({ message: String(message), file: file, line: line });
  return false;
};
